export function mulberry32(seed) {
  let a = seed;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const round2 = (x) => Math.round(x * 100) / 100;
// Числа в пользовательском тексте — по русской типографике (запятая, разряды),
// как fmtNum в калькуляторе. Числовые поля задач не трогаем — только текст.
const fmt = (n) => new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 2 }).format(n);
const pick = (rng, arr) => arr[Math.floor(rng() * arr.length)];
const intStep = (rng, min, max, step) => {
  const n = Math.floor(rng() * ((max - min) / step + 1));
  return min + n * step;
};

